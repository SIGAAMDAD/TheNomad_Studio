#!/usr/bin/env node
// Generated metadata for the frozen OpenAPI contract. No routes are hand-authored.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const spec = JSON.parse(readFileSync(resolve(root, 'CONTRACTS/openapi.json'), 'utf8'));
const out = resolve(root, 'ui/src/generated/operations.ts');
const methods = new Set(['get', 'post', 'put', 'patch', 'delete']);
const seen = new Set();
const deref = (schema, stack = new Set()) => {
  if (!schema) return {};
  if (schema.$ref) {
    const id = schema.$ref.split('/').pop();
    if (stack.has(id)) throw new Error(`recursive schema: ${id}`);
    return deref(spec.components.schemas[id], new Set([...stack, id]));
  }
  if (schema.type === 'array') return { type: 'array', items: deref(schema.items, stack) };
  if (schema.type === 'object') return {
    type: 'object', required: schema.required ?? [],
    properties: Object.fromEntries(Object.entries(schema.properties ?? {}).map(([key, value]) => [key, deref(value, stack)]))
  };
  const resolved = Object.fromEntries(Object.entries(schema).filter(([k]) => ['type', 'format', 'enum', 'description', 'default', 'nullable', 'minimum', 'maximum', 'minLength', 'maxLength'].includes(k)));
  if (Array.isArray(resolved.type) && resolved.type.length === 2 && resolved.type.includes('null')) {
    resolved.type = resolved.type.find((type) => type !== 'null');
    resolved.nullable = true;
  }
  return resolved;
};
const records = {};
for (const [path, route] of Object.entries(spec.paths)) {
  for (const [method, def] of Object.entries(route)) {
    if (!methods.has(method)) continue;
    if (seen.has(def.operationId)) throw new Error('duplicate operation: ' + def.operationId);
    seen.add(def.operationId);
    const params = (def.parameters ?? []).concat(route.parameters ?? []);
    const pathParams = [...path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
    const query = params.filter((p) => p.in === 'query').map((p) => ({ name: p.name, required: !!p.required, schema: deref(p.schema) }));
    const body = def.requestBody?.content?.['application/json']?.schema;
    const response = def.responses?.['200']?.content?.['application/json']?.schema;
    if (!response) throw new Error('missing success schema: ' + def.operationId);
    records[def.operationId] = { method: method.toUpperCase(), path, pathParams, query, body: body ? deref(body) : null, response: deref(response) };
  }
}
if (seen.size !== 72) throw new Error('Expected 72 operations; received ' + seen.size);
const code = '// GENERATED by ui/scripts/generate-api.mjs from CONTRACTS/openapi.json. DO NOT EDIT.\n' +
  'import type { StudioOperationId } from "../../../CONTRACTS/api.types";\n' +
  'export type FieldSchema = { type?: string; format?: string; enum?: readonly string[]; description?: string; default?: unknown; nullable?: boolean; minimum?: number; maximum?: number; minLength?: number; maxLength?: number; required?: readonly string[]; properties?: Record<string, FieldSchema>; items?: FieldSchema };\n' +
  'export interface OperationMeta { readonly method: string; readonly path: string; readonly pathParams: readonly string[]; readonly query: readonly { name: string; required: boolean; schema: FieldSchema }[]; readonly body: FieldSchema | null; readonly response: FieldSchema }\n' +
  'export const operations: Record<StudioOperationId, OperationMeta> = ' + JSON.stringify(records, null, 2) + ';\n';
writeFileSync(out, code);
console.log(`Generated ${seen.size} operation descriptors from frozen OpenAPI.`);
