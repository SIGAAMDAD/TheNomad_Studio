"""R7 design-time production/cabal callable contract (Python >=3.11).

This module describes FROZEN TARGET PORTS, not implemented services.
There are no aliases for any pre-R7 Studio API. Every `Record` crossing a port
must pass the corresponding schema in CONTRACTS/records.schema.json.
All source/provider evidence must be created by a trusted service, not by a model.
StateWriter/SQlite transactions are injected only at P2 composition root.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Protocol, Sequence

Record = Mapping[str, Any]


@dataclass(frozen=True, slots=True)
class Decision:
    allowed: bool
    status: str
    code: str
    affected_ref: str
    evidence_refs: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class Result:
    status: str
    code: str
    record: Record | None = None
    receipt_ref: str | None = None
    evidence_refs: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class SourceFence:
    project_id: str
    repo: str
    branch: str
    expected_parent_commit: str
    resource_scope_digest: str
    feature_id: str
    bible_pair_digest: str


class IdentityPort(Protocol):  # CAB-H: identity+provider boundary
    def authenticate_owner(self, provider_proof_ref: str, action_digest: str) -> Result: ...
    def authenticate_worker(self, provider_proof_ref: str, job_id: str, lease_epoch: int) -> Result: ...
    def verify_external_permission(self, principal_id: str, provider_id: str, action: str, target_ref: str) -> Decision: ...
    def verify_owner_decision(self, proof_ref: str, action: str, subject_digest: str, project_id: str) -> Decision: ...


class BiblePort(Protocol):  # CAB-D: sole activated edition and immutable pair writer
    def propose_edition(self, edition: Record, source_readback: Record) -> Result: ...
    def activate_edition(self, edition_id: str, owner_proof: Decision, expected_active_epoch: int) -> Result: ...
    def snapshot_active_pair(self, project_id: str, feature_scope: Record) -> Result: ...
    def get_clause_bundle(self, bible_pair_digest: str, scope: Record) -> Result: ...
    def verify_clause_provenance(self, clause_refs: Sequence[str], bible_pair_digest: str) -> Decision: ...


class AuthorityPort(Protocol):  # CAB-D: bible/scope/effect impact; NOT impact-category owner gate
    def authorize_effect(self, effect_intent: Record, *, bible_pair_digest: str, contract_digest: str,
                         checked_content: Record) -> Decision: ...
    def assess_bible_conflict(self, feature_id: str, decision_or_diff: Record, bible_pair_digest: str) -> Result: ...
    def authorize_protected_effect(self, effect_intent: Record, owner_proof: Decision) -> Decision: ...


class ProjectPort(Protocol):  # CAB-B: owner project registry / bootstrapping
    def register_project(self, project_spec: Record, authenticated_owner: Result) -> Result: ...
    def set_project_state(self, project_id: str, expected_epoch: int, new_state: str,
                          authenticated_owner: Result) -> Result: ...
    def get_project(self, project_id: str) -> Result: ...
    def list_owner_projects(self, owner_principal_id: str) -> Sequence[Record]: ...


class BriefPort(Protocol):  # CAB-B: sole original owner request writer
    def admit_brief(self, owner_command: Record, owner_identity: Result) -> Result: ...
    def get_original_brief(self, brief_id: str, project_id: str) -> Result: ...
    def amend_brief(self, feature_id: str, amendment: Record, owner_identity: Result) -> Result: ...


class FeatureContractPort(Protocol):  # CAB-B: feature outcomes and requirements writer
    def compile_contract(self, brief_id: str, bible_pair: Record, context_bundle: Record) -> Result: ...
    def get_contract(self, feature_id: str, revision: int) -> Result: ...
    def revise_contract(self, feature_id: str, requested_changes: Record, original_brief: Record,
                        bible_pair_digest: str) -> Result: ...


class DirectorPort(Protocol):  # CAB-J: sole FeatureRun lifecycle writer
    def open_run(self, brief: Record, feature_contract: Record) -> Result: ...
    def advance_run(self, feature_id: str, expected_revision: int, requested_state: str,
                    evidence_receipt: Record) -> Result: ...
    def reconcile_run(self, feature_id: str, observed_state: Record) -> Result: ...
    def get_feature_status(self, feature_id: str, owner_principal_id: str) -> Result: ...


class WorkGraphPort(Protocol):  # CAB-C: single writer for immutable plan revisions
    def plan_feature(self, feature_contract: Record, capability_snapshot: Record) -> Result: ...
    def validate_graph(self, graph: Record, contract_digest: str) -> Decision: ...
    def create_rework(self, feature_id: str, failed_receipt: Record, current_graph_revision: int) -> Result: ...
    def get_ready_tasks(self, feature_id: str, graph_revision: int) -> Sequence[Record]: ...


class SchedulingPort(Protocol):  # CAB-C: tasks, leases, shift attempts
    def enqueue_ready(self, feature_id: str, graph_revision: int, scoped_cabals: Record) -> Result: ...
    def lease_task(self, task_id: str, worker_principal: str, approved_capacity: Decision) -> Result: ...
    def record_checkpoint(self, task_id: str, lease_epoch: int, host_receipt: Record) -> Result: ...
    def finish_attempt(self, task_id: str, lease_epoch: int, verified_artifacts: Record) -> Result: ...
    def fence_expired(self, project_id: str, trusted_now_us: int) -> Result: ...


class CabalPort(Protocol):  # CAB-A: membership, local charter, subgroup writer
    def reserve_cabals(self, feature_id: str, bible_pair_digest: str, required_capabilities: Sequence[str]) -> Result: ...
    def authorize_cabal_task(self, cabal_id: str, worker_principal: str, task: Record) -> Decision: ...
    def open_deliberation(self, cabal_id: str, feature_id: str, scoped_question: Record) -> Result: ...
    def get_cabal_roster(self, project_id: str, cabal_id: str) -> Result: ...


class CouncilPort(Protocol):  # CAB-F: advisory; may choose bible-compliant resolution
    def open_case(self, feature_id: str, conflict: Record, bible_pair_digest: str) -> Result: ...
    def record_dissent(self, case_id: str, dissent: Record) -> Result: ...
    def resolve_case(self, case_id: str, selected_proposal: Record, compliance: Decision) -> Result: ...
    def get_recommendation(self, case_id: str) -> Result: ...


class CapabilityPort(Protocol):  # CAB-G: skills, persona, budget and capacity
    def resolve_capabilities(self, project_id: str, required_skills: Sequence[str], bible_pair_digest: str) -> Result: ...
    def allocate_capabilities(self, feature_contract: Record, graph: Record) -> Result: ...
    def reserve_budget(self, feature_id: str, requested_units: int, feature_budget_digest: str) -> Decision: ...
    def reconcile_spend(self, reservation_id: str, provider_charge_receipt: Record) -> Result: ...


class WorkerHostPort(Protocol):  # CAB-H: genuine host-native effects, never a fake receipt
    def get_capability_manifest(self, provider_id: str) -> Result: ...
    def dispatch_task(self, task: Record, worker_session_ref: str, context_bundle_digest: str) -> Result: ...
    def observe_activation(self, session_id: str, distinct_job_ids: Sequence[str]) -> Result: ...
    def read_checkpoint(self, session_id: str, job_id: str, attempt_epoch: int) -> Result: ...
    def fence_session(self, session_id: str, expected_epoch: int) -> Result: ...


class AgentExecutionPort(Protocol):  # CAB-H: structured planner/author/reviewer invocations
    def start_agent_job(self, job_spec: Record, context_bundle_digest: str,
                        required_capabilities: Sequence[str]) -> Result: ...
    def observe_agent_result(self, job_id: str, attempt_epoch: int) -> Result: ...
    def request_agent_cancel(self, job_id: str, attempt_epoch: int) -> Result: ...


class ContextPort(Protocol):  # CAB-I: source/canon/knowledge projection; not bible authority
    def build_bundle(self, project_id: str, brief_id: str, bible_pair_digest: str,
                     source_fence: SourceFence | None) -> Result: ...
    def get_verified_excerpt(self, bundle_digest: str, excerpt_ref: str) -> Result: ...
    def apply_accepted_feature_outcomes(self, feature_id: str, quality_receipt: Record) -> Result: ...


class ProjectAdapterPort(Protocol):  # CAB-I: real game/engine adapter selected by Technical Bible
    def resolve_adapter(self, project_id: str, technical_edition_id: str, pinned_source_commit: str) -> Result: ...
    def run_import(self, project_id: str, branch_commit: str, adapter_ref: str, trusted_runner: Record) -> Result: ...
    def run_build(self, project_id: str, branch_commit: str, adapter_ref: str, trusted_runner: Record) -> Result: ...
    def run_feature_smoke(self, feature_id: str, branch_commit: str, check_ids: Sequence[str],
                          adapter_ref: str, trusted_runner: Record) -> Result: ...
    def verify_assets(self, feature_id: str, branch_commit: str, asset_manifest_ref: str,
                      adapter_ref: str, trusted_runner: Record) -> Result: ...


class ArtifactPort(Protocol):  # CAB-I: immutable bytes, typed manifests
    def submit_artifacts(self, task_id: str, lease_epoch: int, manifests: Sequence[Record], source_proofs: Record) -> Result: ...
    def verify_artifact_bytes(self, manifest_ref: str, expected_digest: str) -> Result: ...
    def get_feature_manifest(self, feature_id: str, contract_digest: str) -> Result: ...


class RepositoryPort(Protocol):  # CAB-I: local/remote feature branch scope only
    def prepare_feature_patch(self, feature_id: str, patches: Sequence[Record], fence: SourceFence) -> Result: ...
    def integrate_feature(self, feature_id: str, graph_revision: int, reviewed_artifacts: Record,
                          fence: SourceFence) -> Result: ...
    def readback_commit(self, effect_ref: str, repo: str, branch: str) -> Result: ...
    def inspect_branch(self, project_id: str, repo: str, branch: str) -> Result: ...


class EffectPort(Protocol):  # CAB-I: external effects, once-only with readback
    def prepare_effect(self, intent: Record, scope_decision: Decision, provider_permission: Decision) -> Result: ...
    def dispatch_once(self, effect_id: str, idempotency_key: str) -> Result: ...
    def reconcile_readback(self, effect_id: str, authoritative_provider_observation: Record) -> Result: ...


class QualityPort(Protocol):  # CAB-E: independent evidence and QA_READY
    def review_submission(self, task_id: str, subject_digest: str, author_lineage: Record,
                          reviewer_identity: Result) -> Result: ...
    def run_production_gates(self, feature_id: str, tested_commit: str, manifest_ref: str,
                             project_adapter_ref: str) -> Result: ...
    def issue_qa_ready(self, feature_id: str, source_commit: str, feature_contract_digest: str,
                       test_and_bible_evidence: Record) -> Result: ...
    def record_independent_qa(self, feature_id: str, source_commit: str, qa_verdict: Record,
                              reviewer_identity: Result) -> Result: ...


class CommandPort(Protocol):  # CAB-J: single owner command entry; transport not identity
    def submit_owner_command(self, command: Record, verified_identity: Result) -> Result: ...
    def get_feature_status(self, owner_id: str, feature_id: str) -> Result: ...
    def get_studio_status(self, owner_id: str, project_id: str | None) -> Result: ...


class OversightNoticePort(Protocol):  # CAB-H: private signed notice only
    def ingest_signed_notice(self, notice: Record, trusted_signature: Record) -> Result: ...
