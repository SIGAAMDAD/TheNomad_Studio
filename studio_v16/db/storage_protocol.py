"""Trusted backend-neutral storage boundary; never a public authentication DTO."""
from typing import Protocol
from .store import GatewayContext


class DurableStore(Protocol):
    def execute(self, command: dict, context: GatewayContext) -> dict: ...
    def command(self, command: dict, context: GatewayContext) -> dict: ...
    def record_event(self, envelope: dict, context: GatewayContext) -> str: ...
    def reserve_outbox_delivery(self, context: GatewayContext, **limits) -> list: ...
    def mark_delivery_retry(self, outbox_id, claim_token, reason, context, **limits): ...
    def reconcile_outbox(self, outbox_id, readback_state, observed_sha256, provider_ref, context, **limits): ...
    def shadow_import(self, import_id, source_kind, source_ref, source_revision, source_json, context): ...
    def reconcile_shadow(self, source_kind, source_ref, source_revision, expected_digest, context): ...
    def save_resume_capsule(self, capsule: dict, context: GatewayContext): ...
    def load_resume_capsule(self, job_id: str, context: GatewayContext): ...
    def resume_capsule(self, job_id: str, context: GatewayContext): ...
    def verify_gateway_state(self, job_id, grant_id, state): ...
    def reserve_gateway_intent(self, intent, principal_id, state, state_revision, payload_sha256): ...
    def authorize_gateway_effect(self, intent, state) -> bool: ...
    def recorded_gateway_intent(self, publication_id, idempotency_key): ...
    def mark_gateway_conflict(self, publication_id, idempotency_key, state, state_revision, receipt): ...
    def reconcile_gateway_intent(self, publication_id, idempotency_key, state, state_revision, receipt): ...
